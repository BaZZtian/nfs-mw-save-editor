def canon_name(marker_id: int) -> Optional[str]:
    """In-game marker title, or None (DECAL/PAINT are nameless in FE)."""
    entry = MARKER_CANON.get(marker_id)
    return entry.name if entry else None


def canon_description(marker_id: int) -> Optional[str]:
    """In-game marker description, or None."""
    entry = MARKER_CANON.get(marker_id)
    return entry.description if entry else None


def canon_fe_category(marker_id: int) -> Optional[str]:
    """The game's own FE category title for a marker, or None."""
    entry = MARKER_CANON.get(marker_id)
    return entry.fe_category if entry else None


