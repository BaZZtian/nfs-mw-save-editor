"""Canonical marker (Junkman token) display names from the game's FE data.

Index = ePossibleMarker (see core/junkman.py; MARKER_LAST = 21). Source:
MarkerSelectInfo table in speed.exe v1.3 (file offset 0x505ED0, 22 records
x 0x1C, stored in display order with the true enum id in a chain field),
label hashes resolved through LANGUAGES/Labels.bin and display strings
through LANGUAGES/English.bin (chunk 0x00039000 hash tables).

FE facts worth knowing:
- DECAL (15) and PAINT (16) are nameless in the FE table (null label
  hashes) — the marker-select screen never names them; they are absent
  here and callers must keep their own fallback names.
- INDUCTION (4) is displayed by the game as "Unique Supercharger
  Upgrades" (label MARKER_NAME_SUPERCHARGER); turbo and supercharger are
  one marker type, split by the marker's Param at grant time.
- The engine groups markers into FOUR FE categories (Performance / Parts /
  Visual / Bonus Markers); the editor keeps its historical 3-way grouping
  (Performance / Visual / Police) on purpose — fe_category here is the
  game's grouping, not the editor's.
- The CASH (19) description carries the engine's printf placeholder
  ("%$d") verbatim.

Generated by RE/tools/gen_token_names.py. Do not edit by hand.
"""
